//go:build integration

package db_test

import (
	"net/url"
	"strings"
	"testing"

	"github.com/jackc/pgx/v5"

	"github.com/licetum/licetum/core/db"
)

func TestContract_OPS08_LegacySchemaIsRefusedWithoutMutation(t *testing.T) {
	for _, schema := range []string{"public", "legacy"} {
		t.Run(schema, func(t *testing.T) {
			ctx, pool, cfg := seededPool(t)
			namespace := pgx.Identifier{schema}.Sanitize()
			if _, err := pool.Exec(ctx, "CREATE SCHEMA IF NOT EXISTS "+namespace); err != nil {
				t.Fatal(err)
			}
			versionTable := pgx.Identifier{schema, "goose_db_version"}.Sanitize()
			markerTable := pgx.Identifier{schema, "legacy_marker"}.Sanitize()
			if _, err := pool.Exec(ctx, "CREATE TABLE "+versionTable+` (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,version_id bigint NOT NULL,is_applied boolean NOT NULL,tstamp timestamp NOT NULL DEFAULT now());
   INSERT INTO `+versionTable+`(version_id,is_applied) VALUES(0,true),(8,true);
   CREATE TABLE `+markerTable+`(value text NOT NULL);INSERT INTO `+markerTable+` VALUES('untouched')`); err != nil {
				t.Fatal(err)
			}
			if schema == "legacy" {
				if _, err := pool.Exec(ctx, `CREATE SCHEMA fresh`); err != nil {
					t.Fatal(err)
				}
				uri, err := url.Parse(db.NormalizeDSN(cfg.DB.URI))
				if err != nil {
					t.Fatal(err)
				}
				query := uri.Query()
				query.Set("search_path", "fresh,legacy")
				uri.RawQuery = query.Encode()
				conn := cfg.DB
				conn.URI = uri.String()
				scoped, err := db.Connect(ctx, conn)
				if err != nil {
					t.Fatal(err)
				}
				t.Cleanup(scoped.Close)
				pool = scoped
			}
			snapshot := func() string {
				t.Helper()
				var raw string
				query := `SELECT jsonb_build_object(
    'objects',(SELECT jsonb_agg(jsonb_build_array(n.nspname,c.relname,c.relkind) ORDER BY n.nspname,c.relname,c.relkind) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname !~ '^pg_' AND n.nspname<>'information_schema'),
    'versions',(SELECT jsonb_agg(to_jsonb(v) ORDER BY id) FROM ` + versionTable + ` v),
    'marker',(SELECT jsonb_agg(to_jsonb(m)) FROM ` + markerTable + ` m),
    'sequence',pg_sequence_last_value(pg_get_serial_sequence($1,'id')::regclass))::text`
				if err := pool.QueryRow(ctx, query, schema+".goose_db_version").Scan(&raw); err != nil {
					t.Fatal(err)
				}
				return raw
			}
			before := snapshot()
			for _, operation := range []string{"migrate", "up-to", "down-to"} {
				var err error
				switch operation {
				case "migrate":
					err = db.Migrate(ctx, pool, cfg)
				case "up-to":
					err = db.MigrateUpTo(ctx, pool, db.LatestMigration())
				case "down-to":
					err = db.MigrateDownTo(ctx, pool, 0)
				}
				if err == nil {
					t.Fatalf("%s accepted a v0.1.x database", operation)
				}
				for _, part := range []string{"Licetum v0.1.x", "installed migration version 8", "no upgrade path", "new database", "docker compose down -v"} {
					if !strings.Contains(err.Error(), part) {
						t.Errorf("%s error %q lacks %q", operation, err, part)
					}
				}
				if after := snapshot(); after != before {
					t.Fatalf("%s mutated the legacy database: before %s after %s", operation, before, after)
				}
				var created bool
				if err := pool.QueryRow(ctx, `SELECT to_regclass('goose_db_version_v2') IS NOT NULL`).Scan(&created); err != nil {
					t.Fatal(err)
				}
				if created {
					t.Fatalf("%s created the v2 version table on a refused database", operation)
				}
			}
		})
	}
}
